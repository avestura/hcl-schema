// Regenerates the meta-schema reference page from the meta-schema itself.
//
// The output is committed, so the site builds without Go installed. Run this
// whenever schema/draft/<id>/.schema.hcl changes; CI checks that the committed
// copy is up to date.

const { spawnSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const repoRoot = path.resolve(__dirname, '..', '..');
const out = path.resolve(__dirname, '..', 'docs', 'reference', 'meta-schema.md');
const schema = path.join('schema', 'draft', '2026-09', '.schema.hcl');

const header = `---
id: meta-schema
title: Meta-schema reference
sidebar_position: 9
description: Every key a *.schema.hcl document may contain, generated from the meta-schema.
---

{/* Generated by website/scripts/gen-reference.js. Do not edit by hand. */}

This page is generated from [\`${schema.replace(/\\/g, '/')}\`](https://github.com/avestura/hcl-schema/blob/main/${schema.replace(/\\/g, '/')})
by \`hclschema docs\` — the same command you would run against your own schema.

`;

const r = spawnSync(
  'go',
  ['run', './cmd/hclschema-cli', 'docs', '--no-frontmatter', '--heading-offset', '1', '--title', 'Meta-schema', schema],
  { cwd: repoRoot, encoding: 'utf8', maxBuffer: 32 * 1024 * 1024 },
);
if (r.error) throw r.error;
if (r.status !== 0) {
  process.stderr.write(r.stderr || '');
  throw new Error(`hclschema docs exited with ${r.status}`);
}

fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, header + r.stdout, 'utf8');
console.log(`wrote ${path.relative(repoRoot, out)}`);
